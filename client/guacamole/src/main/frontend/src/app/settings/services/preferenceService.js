/**
 * A service for setting and retrieving browser-local preferences. Preferences
 * may be any JSON-serializable type.
 */
angular.module('settings').provider('preferenceService', ['$injector',
    function preferenceServiceProvider($injector) {

    // Required providers
    var localStorageServiceProvider = $injector.get('localStorageServiceProvider');

    /**
     * Reference to the provider itself.
     *
     * @type preferenceServiceProvider
     */
    var provider = this;

    /**
     * The storage key of Guacamole preferences within local storage.
     *
     * @type String
     */
    var GUAC_PREFERENCES_STORAGE_KEY = "GUAC_PREFERENCES";

    /**
     * All valid input method type names.
     *
     * @type Object.<String, String>
     */
    var inputMethods = {

        /**
         * No input method is used. Keyboard events are generated from a
         * physical keyboard.
         *
         * @constant
         * @type String
         */
        NONE : 'none',

        /**
         * Keyboard events will be generated from the Guacamole on-screen
         * keyboard.
         *
         * @constant
         * @type String
         */
        OSK : 'osk',

        /**
         * Keyboard events will be generated by inferring the keys necessary to
         * produce typed text from an IME (Input Method Editor) such as the
         * native on-screen keyboard of a mobile device.
         *
         * @constant
         * @type String
         */
        TEXT : 'text',

        /** Native keyboard with an explicit show/hide control. */
        NATIVE : 'native'

    };

    /**
     * Returns the key of the language currently in use within the browser.
     * This is not necessarily the user's desired language, but is rather the
     * language user by the browser's interface.
     *
     * @returns {String}
     *     The key of the language currently in use within the browser.
     */
    var getDefaultLanguageKey = function getDefaultLanguageKey() {

        // Pull browser language, falling back to US English
        var language = (navigator.languages && navigator.languages[0])
                     || navigator.language
                     || navigator.browserLanguage
                     || 'en';

        // Convert to format used internally
        return language.replace(/-/g, '_');

    };
    
    /**
     * Return the timezone detected for the current browser session
     * by the JSTZ timezone library.
     * 
     * @returns String
     *     The name of the currently-detected timezone in IANA zone key
     *     format (Olson time zone database).
     */
    var getDetectedTimezone = function getDetectedTimezone() {
        return jstz.determine().name();
    };

    // iPadOS can use a desktop Mac user agent. Touch points distinguish that
    // mode from a Mac. A platform fallback also covers iPhone/iPod browsers
    // which mask or omit their device name in the user agent.
    var isIOS = /iPad|iPhone|iPod/i.test(navigator.userAgent || '')
        || /iPad|iPhone|iPod/i.test(navigator.platform || '')
        || (navigator.platform === 'MacIntel' && navigator.maxTouchPoints > 1);

    /**
     * All currently-set preferences, as name/value pairs. Each property name
     * corresponds to the name of a preference.
     *
     * @type Object.<String, Object>
     */
    this.preferences = {

        /** Private video decoding is experimental and opt-in. Legacy true means AVC420. */
        experimentalAvc420 : false,
        experimentalVideoMode : null,

        /** Shortcut hint for Greenmole RDP; never changes local key events. */
        keyboardMode : 'auto',

        /**
         * Whether translation of touch to mouse events should emulate an
         * absolute pointer device, or a relative pointer device.
         * 
         * @type Boolean
         */
        emulateAbsoluteMouse : !isIOS,

        /**
         * The default input method. This may be any of the values defined
         * within preferenceService.inputMethods.
         *
         * @type String
         */
        inputMethod : isIOS ? inputMethods.NATIVE : inputMethods.NONE,
        
        /**
         * The key of the desired display language.
         * 
         * @type String
         */
        language : getDefaultLanguageKey(),
        
        /**
         * The number of recent connections to display.
         * 
         * @type {!number}
         */
        numberOfRecentConnections: 6,
        
        /**
         * Whether or not to show the "Recent Connections" section.
         * 
         * @type {!boolean}
         */
        showRecentConnections : true,
        
        /**
         * The timezone set by the user, in IANA zone key format (Olson time
         * zone database).
         * 
         * @type String
         */
        timezone : getDetectedTimezone()

    };

    // Get stored preferences from localStorage
    var storedPreferences = localStorageServiceProvider.getItem(GUAC_PREFERENCES_STORAGE_KEY);
    if (storedPreferences)
        angular.extend(provider.preferences, storedPreferences);

    // Older releases automatically saved the desktop's absolute mouse
    // default, even when the user never chose it. Apply the requested iOS
    // trackpad default once, then preserve every later explicit mouse choice.
    // Keep future markers intact if an older build is used for rollback.
    var migrateIOSMouse = isIOS && !(storedPreferences
        && typeof storedPreferences.iosTouchpadDefaultVersion === 'number'
        && storedPreferences.iosTouchpadDefaultVersion >= 1);
    if (migrateIOSMouse) {
        provider.preferences.emulateAbsoluteMouse = false;
        provider.preferences.iosTouchpadDefaultVersion = 1;
    }

    // Earlier builds automatically persisted NONE on navigation, so its
    // presence alone cannot distinguish an old desktop default from a choice.
    // Upgrade that legacy value once; keep existing text/OSK/native choices and
    // every subsequent explicit choice, including NONE. Use an independent
    // marker because the mouse migration may already have run on this browser.
    var migrateIOSKeyboard = isIOS && !(storedPreferences
        && typeof storedPreferences.iosNativeKeyboardDefaultVersion === 'number'
        && storedPreferences.iosNativeKeyboardDefaultVersion >= 1);
    if (migrateIOSKeyboard) {
        if (provider.preferences.inputMethod === inputMethods.NONE)
            provider.preferences.inputMethod = inputMethods.NATIVE;
        provider.preferences.iosNativeKeyboardDefaultVersion = 1;
    }

    // Language and keyboard layout are intentionally not guessed from locale.
    var isMacKeyboard = isIOS || /Mac/i.test(navigator.platform || '')
        || /Macintosh|Mac OS X/i.test(navigator.userAgent || '');
    var keyboardModes = ['auto', 'windows', 'mac', 'physical'];
    if (keyboardModes.indexOf(provider.preferences.keyboardMode) === -1)
        provider.preferences.keyboardMode = 'auto';

    // Factory method required by provider
    this.$get = ['$injector', function preferenceServiceFactory($injector) {

        // Required services
        var $rootScope          = $injector.get('$rootScope');
        var $window             = $injector.get('$window');
        var localStorageService = $injector.get('localStorageService');

        var service = {};

        /**
         * All valid input method type names.
         *
         * @type Object.<String, String>
         */
        service.inputMethods = inputMethods;

        /**
         * All currently-set preferences, as name/value pairs. Each property name
         * corresponds to the name of a preference.
         *
         * @type Object.<String, Object>
         */
        service.preferences = provider.preferences;

        /** Resolve the browser-local preference only when starting a connection. */
        service.getResolvedKeyboardMode = function getResolvedKeyboardMode() {
            var mode = service.preferences.keyboardMode;
            if (keyboardModes.indexOf(mode) === -1 || mode === 'auto')
                return isMacKeyboard ? 'mac' : 'windows';
            return mode;
        };

        /** Save a supported explicit choice; established sessions are unchanged. */
        service.setKeyboardMode = function setKeyboardMode(mode) {
            if (keyboardModes.indexOf(mode) === -1)
                return false;
            service.preferences.keyboardMode = mode;
            service.save();
            return true;
        };

        /**
         * Persists the current values of all preferences, if possible.
         */
        service.save = function save() {
            localStorageService.setItem(GUAC_PREFERENCES_STORAGE_KEY, service.preferences);
        };

        // Commit migrations before any menu choice or navigation can occur.
        // Otherwise a reload could reset an intentional mouse/keyboard choice.
        if (migrateIOSMouse || migrateIOSKeyboard)
            service.save();

        // Persist settings when window is unloaded
        $window.addEventListener('unload', service.save);

        // Persist settings upon navigation 
        $rootScope.$on('$routeChangeSuccess', function handleNavigate() {
            service.save();
        });

        // Persist settings upon logout
        $rootScope.$on('guacLogout', function handleLogout() {
            service.save();
        });

        return service;

    }];

}]);
